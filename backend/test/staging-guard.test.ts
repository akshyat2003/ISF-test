import { describe, expect, it } from "vitest";
import { APPROVED_STAGING_REFS, assertApprovedStagingTarget, createdAtOrAfter, CreatedUsers, type DeleteResult } from "../scripts/staging-guard.js";

const REF = APPROVED_STAGING_REFS[0]!;
const ok = { confirm: "this-is-staging", expectedRef: REF, supabaseUrl: `https://${REF}.supabase.co` };

describe("staging target guard", () => {
  it("accepts only the approved ref with its exact URL and the confirmation phrase", () => {
    expect(assertApprovedStagingTarget(ok)).toBe(REF);
    expect(assertApprovedStagingTarget({ ...ok, supabaseUrl: `https://${REF}.supabase.co/` })).toBe(REF);
  });
  it.each([
    ["missing confirmation", { ...ok, confirm: undefined }],
    ["wrong confirmation", { ...ok, confirm: "yes" }],
    ["missing expected ref", { ...ok, expectedRef: undefined }],
    ["unapproved ref (personal project)", { ...ok, expectedRef: "owsbizpdcdzcvplvxfnt", supabaseUrl: "https://owsbizpdcdzcvplvxfnt.supabase.co" }],
    ["URL for a different project", { ...ok, supabaseUrl: "https://owsbizpdcdzcvplvxfnt.supabase.co" }],
    ["look-alike host", { ...ok, supabaseUrl: `https://${REF}.supabase.co.evil.example` }],
    ["subdomain trick", { ...ok, supabaseUrl: `https://evil.${REF}.supabase.co` }],
    ["http", { ...ok, supabaseUrl: `http://${REF}.supabase.co` }],
    ["port", { ...ok, supabaseUrl: `https://${REF}.supabase.co:8443` }],
    ["path", { ...ok, supabaseUrl: `https://${REF}.supabase.co/rest/v1` }],
    ["credentials", { ...ok, supabaseUrl: `https://u:p@${REF}.supabase.co` }],
    ["not a URL", { ...ok, supabaseUrl: "chiafggvergjwliqvlwv" }],
  ])("refuses: %s", (_n, env) => {
    expect(() => assertApprovedStagingTarget(env)).toThrow();
  });
});

describe("cleanup ownership", () => {
  const start = new Date("2026-10-15T10:00:00Z");
  const after = "2026-10-15T10:00:05Z";

  it("never records a pre-existing account, whatever its email looks like", () => {
    const c = new CreatedUsers(start, "run1");
    for (const email of ["manager@example.com", "staff@isf.org", "admin@dev.local", "sj-staging-run1-x@example.com"]) {
      expect(c.recordIfFresh({ id: email, email, created_at: after }, true)).toBe(false);
    }
    expect(c.list()).toEqual([]);
  });

  it("records a new account only when its address was generated by this run", () => {
    const c = new CreatedUsers(start, "run1");
    const mine = c.ownedEmail("applicant");
    expect(c.recordIfFresh({ id: "u1", email: "manager@example.com", created_at: after }, false)).toBe(false);   // not ours
    expect(c.recordIfFresh({ id: "u2", email: mine, created_at: "2026-10-15T09:59:59Z" }, false)).toBe(false);   // older than the run
    expect(c.recordIfFresh({ id: "u3", email: mine.toUpperCase(), created_at: after }, false)).toBe(true);
    expect(c.list()).toEqual(["u3"]);
  });

  it("records a phone-only user only if the test number was unused before the run", () => {
    const c = new CreatedUsers(start, "run1");
    expect(c.recordIfFreshPhone({ id: "p0", phone: "919000000001", created_at: after }, true, "+91 90000 00001")).toBe(false);   // existed
    expect(c.recordIfFreshPhone({ id: "p1", phone: "919000000002", created_at: after }, false, "+919000000001")).toBe(false);   // other number
    expect(c.recordIfFreshPhone({ id: "p2", phone: "919000000001", created_at: "2026-10-15T09:00:00Z" }, false, "+919000000001")).toBe(false);
    expect(c.recordIfFreshPhone({ id: "p3", phone: "919000000001", created_at: after }, false, "+91 90000 00001")).toBe(true);
    expect(c.list()).toEqual(["p3"]);
  });

  it("records users from a successful createUser call; only a confirmed delete removes them", async () => {
    const c = new CreatedUsers(start, "run1");
    c.recordCreated({ id: "u9" });
    expect(c.has("u9")).toBe(true);
    expect(await c.deleteOwned("u9", async () => ({ error: null }))).toEqual({ ok: true });
    expect(c.list()).toEqual([]);
  });
});

describe("timestamps fail closed", () => {
  const start = new Date("2026-10-15T10:00:00Z");
  it.each([["malformed", "not-a-date"], ["empty", ""], ["missing", undefined], ["older", "2026-10-15T09:59:59Z"]])(
    "%s created_at is never treated as created by this run", (_n, value) => {
      expect(createdAtOrAfter(value as string | undefined, start)).toBe(false);
      const c = new CreatedUsers(start, "run1");
      const mine = c.ownedEmail("applicant");
      expect(c.recordIfFresh({ id: "u", email: mine, created_at: value as string | undefined }, false)).toBe(false);
      expect(c.recordIfFreshPhone({ id: "p", phone: "919000000001", created_at: value as string | undefined }, false, "+919000000001")).toBe(false);
      expect(c.list()).toEqual([]);
    });
  it("accepts a valid timestamp at or after the start", () => {
    expect(createdAtOrAfter("2026-10-15T10:00:00Z", start)).toBe(true);
  });
  it("refuses an invalid start time", () => {
    expect(() => new CreatedUsers(new Date("nope"), "run1")).toThrow();
  });
});

describe("cleanup reports failures and keeps tracking undeleted users", () => {
  const start = new Date("2026-10-15T10:00:00Z");
  const owned = () => {
    const c = new CreatedUsers(start, "run1");
    c.recordCreated({ id: "ok-1" });
    c.recordCreated({ id: "err-1" });
    c.recordCreated({ id: "throw-1" });
    return c;
  };
  const del = async (id: string): Promise<DeleteResult> => {
    if (id.startsWith("err")) return { error: { message: "User not allowed" } };
    if (id.startsWith("throw")) throw new Error("network down");
    return { error: null };
  };

  it("drops an id only after a confirmed deletion", async () => {
    const c = owned();
    expect(await c.deleteOwned("err-1", del)).toEqual({ ok: false, message: "User not allowed" });
    expect(c.has("err-1")).toBe(true);
    expect(await c.deleteOwned("throw-1", del)).toEqual({ ok: false, message: "network down" });
    expect(c.has("throw-1")).toBe(true);
    expect(await c.deleteOwned("ok-1", del)).toEqual({ ok: true });
    expect(c.has("ok-1")).toBe(false);
  });

  it("never calls delete for an id it does not own", async () => {
    const c = owned();
    let called = false;
    const r = await c.deleteOwned("pre-existing-staff", async () => { called = true; return { error: null }; });
    expect(r.ok).toBe(false);
    expect(called).toBe(false);
  });

  it("cleanupAll lists every failure instead of reporting a clean run", async () => {
    const report = await owned().cleanupAll(del);
    expect(report.deleted).toEqual(["ok-1"]);
    expect(report.failed).toEqual([{ id: "err-1", message: "User not allowed" }, { id: "throw-1", message: "network down" }]);
  });
});
